# 5. USG% Líderes
# ============================================================

def get_usage_stars(season: str, season_type: str, min_games: int = 30):

    players = leaguedashplayerstats.LeagueDashPlayerStats(
        season=season,
        season_type_all_star=season_type,
        measure_type_detailed_defense="Advanced",
        per_mode_detailed="PerGame"
    ).get_data_frames()[0]

    players = players[["PLAYER_NAME", "TEAM_ID", "GP", "USG_PCT"]]
    players = players[players["GP"] >= min_games]

    result = []

    for tid in teams_lookup["TEAM_ID"]:
        team_df = players[players["TEAM_ID"] == tid].sort_values("USG_PCT", ascending=False).head(2)
        if len(team_df) < 2:
            continue

        result.append({
            "TEAM_ID": tid,
            "TEAM_NAME": teams_lookup.loc[teams_lookup["TEAM_ID"] == tid, "TEAM_NAME"].values[0],
            "LEADER_1": team_df.iloc[0]["PLAYER_NAME"],
            "USG_L1": round(team_df.iloc[0]["USG_PCT"], 1),
            "LEADER_2": team_df.iloc[1]["PLAYER_NAME"],
            "USG_L2": round(team_df.iloc[1]["USG_PCT"], 1)
        })

    return pd.DataFrame(result)